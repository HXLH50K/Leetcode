class Solution:
    def countCommas(self, n: int) -> int:
        if n < 10**3:
            return 0
        if n < 10**6:
            return n - 999
        if n < 10**9:
            return (n - 999999) * 2 + (999999 - 999)
        if n < 10**12:
            return (n - 999999999) * 3 + (999999999 - 999999) * 2 + (999999 - 999)
        if n < 10**15:
            return (
                (n - 999999999999) * 4
                + (999999999999 - 999999999) * 3
                + (999999999 - 999999) * 2
                + (999999 - 999)
            )
        return (
            (n - 999999999999999) * 5
            + (999999999999999 - 999999999999) * 4
            + (999999999999 - 999999999) * 3
            + (999999999 - 999999) * 2
            + (999999 - 999)
        )
